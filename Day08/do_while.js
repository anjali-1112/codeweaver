// Print 1 → 5 using do...while
let x = 1;
do{
    console.log(x);
    x++;
}while(x<=5);

console.log("---------");
// Print 10 → 1 using do...while
let y = 10;
do{
    console.log(y);
    y--;
}while(y>=1)
console.log("---------");

// Print even numbers 2 → 20 using do...while
