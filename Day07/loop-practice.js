// Write separate programs.

// Print 10 → 1
let n = 10 ;
while(n>=1){
    console.log(n);
    n--;
}
console.log("--------------------");

// Print Even Numbers  2 → 20
let x = 2 ;
while(x<=20){
    console.log(x);
    x+=2;
}

console.log("--------------------");

// Print Odd Numbers 1 → 19
let y = 1 ;
while(y<=19){
    console.log(y);
    y+=2;
}
console.log("--------------------");
// Print Multiples of 5 // 5 → 50
let num = 1 ;
while (num<=10){
    console.log(num*5);
    num++;
}

console.log("--------------------");
