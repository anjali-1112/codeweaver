let n = 1 ;
while(n<=50) {
    console.log("Number: "+ n);
    if(n%2 == 0){        
        console.log("Even: "+ n);
    }
    if(n%2 != 0){        
        console.log("Odd: "+ n);
    }
    if(n%3 == 0){        
        console.log("Multiples of 3: "+ n);
    }
    if(n%5 == 0){        
        console.log("Multiples of 5: "+ n);
    }
    n++ ;
}

